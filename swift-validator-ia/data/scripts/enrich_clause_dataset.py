def _count(records: list, field: str) -> dict:
    return dict(Counter(r[field] for r in records))


def main():
    print("=" * 60)
    print("  Enrichissement dataset clause_classification.jsonl")
    print("=" * 60)

    # 1. Charger dataset existant
    records_orig = []
    with open(DATASET_PATH, encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if line:
                try:
                    records_orig.append(json.loads(line))
                except json.JSONDecodeError:
                    pass
    print(f"\n  Dataset original : {len(records_orig)} exemples")
    print(f"  Importance avant : {_count(records_orig, 'importance')}")

    # 2. Backup
    backup = DATASET_PATH.with_suffix(f".backup_{datetime.now().strftime('%Y%m%d_%H%M%S')}.jsonl")
    shutil.copy(DATASET_PATH, backup)
    print(f"  Backup -> {backup.name}")

    # 3. Remap importance -> 3 niveaux
    remapped = 0
    for r in records_orig:
        old_imp = r.get("importance", "medium")
        new_imp = IMPORTANCE_MAP.get(old_imp, "medium")
        if old_imp != new_imp:
            remapped += 1
        r["importance"] = new_imp
    print(f"  Remapping : {remapped} exemples modifies")
    print(f"  Importance apres remap : {_count(records_orig, 'importance')}")

    # 4. Construire les nouveaux exemples
    new_records = []
    for clause_type, imp_dict in NEW_EXAMPLES.items():
        for importance, texts in imp_dict.items():
            for i, text in enumerate(texts):
                new_records.append({
                    "text":       text,
                    "type":       clause_type,
                    "importance": importance,
                    "source_id":  f"enrich_{clause_type[:3]}_{importance[:3]}_{i:03d}",
                    "swift_type": "MT700",
                    "augmented":  True,
                })
    print(f"\n  Nouveaux exemples : {len(new_records)}")

    # 5. Fusion + deduplication simple (texte exact)
    existing_texts = {r["text"].strip().upper() for r in records_orig}
    added = 0
    for r in new_records:
        key = r["text"].strip().upper()
        if key not in existing_texts:
            records_orig.append(r)
            existing_texts.add(key)
            added += 1
    print(f"  Apres deduplication : {added} nouveaux ajouts")

    # 6. Shuffle + sauvegarde
    random.seed(42)
    random.shuffle(records_orig)

    with open(DATASET_PATH, "w", encoding="utf-8") as f:
        for r in records_orig:
            f.write(json.dumps(r, ensure_ascii=False) + "\n")

    print(f"\n  Dataset final : {len(records_orig)} exemples")
    print(f"  Types      : {_count(records_orig, 'type')}")
    print(f"  Importance : {_count(records_orig, 'importance')}")
    print(f"\n  Sauvegarde -> {DATASET_PATH}")
    print("=" * 60)


if __name__ == "__main__":
    main()
