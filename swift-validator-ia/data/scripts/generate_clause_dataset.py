def load_existing():
    records = []
    with open(DATASET_PATH, encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if not line:
                continue
            try:
                records.append(json.loads(line))
            except json.JSONDecodeError:
                pass
    return records


def signature(text: str) -> str:
    return hashlib.md5(text.strip().upper().encode()).hexdigest()


def main():
    random.seed(RANDOM_SEED)

    print("=" * 65)
    print("  Generation de clauses SWIFT LC manquantes")
    print("=" * 65)

    existing = load_existing()
    existing_sigs = {signature(r["text"]) for r in existing}

    from collections import defaultdict, Counter
    types  = ["document_condition","shipment_condition","payment_condition",
              "compliance_condition","tolerance_condition"]
    levels = ["high","medium","normal"]

    matrix = defaultdict(Counter)
    for r in existing:
        matrix[r["type"]][r.get("importance","?")] += 1

    # Backup
    backup = DATASET_PATH.with_suffix(
        f".backup_{datetime.now().strftime('%Y%m%d_%H%M%S')}.jsonl"
    )
    import shutil
    shutil.copy(DATASET_PATH, backup)
    print(f"\n  Backup -> {backup.name}")

    new_records = []
    stats = {}

    for t in types:
        for l in levels:
            current = matrix[t][l]
            needed  = max(0, TARGET_PER_CELL - current)
            if needed == 0:
                print(f"  {t:<25} {l:<8} OK ({current})")
                continue

            key = (t, l)
            if key not in TEMPLATES:
                print(f"  {t:<25} {l:<8} SKIP (no templates)")
                continue

            pool = TEMPLATES[key]
            generated = 0
            attempts  = 0
            max_attempts = needed * 20

            while generated < needed and attempts < max_attempts:
                attempts += 1
                fn   = random.choice(pool)
                text = fn().strip()
                # Normalize spaces
                text = " ".join(text.split())
                sig  = signature(text)
                if sig not in existing_sigs:
                    existing_sigs.add(sig)
                    new_records.append({
                        "text":       text,
                        "type":       t,
                        "importance": l,
                        "source_id":  f"gen_{t[:3]}_{l[:3]}_{generated:04d}",
                        "swift_type": "MT700",
                        "augmented":  True,
                    })
                    generated += 1

            stats[key] = (current, generated)
            print(f"  {t:<25} {l:<8} +{generated:>3} (was {current:>3}, now {current+generated:>3})")

    # Merge + shuffle + save
    all_records = existing + new_records
    random.shuffle(all_records)

    with open(DATASET_PATH, "w", encoding="utf-8") as f:
        for r in all_records:
            f.write(json.dumps(r, ensure_ascii=False) + "\n")

    # Final stats
    from collections import Counter as C
    final = defaultdict(C)
    for r in all_records:
        final[r["type"]][r.get("importance","?")] += 1

    print(f"\n  Total genere     : {len(new_records)}")
    print(f"  Dataset total    : {len(all_records)}")
    print(f"\n  Distribution finale :")
    print(f"  {'':25}  {'HIGH':>6}  {'MEDIUM':>8}  {'NORMAL':>8}  {'TOTAL':>7}")
    print("  " + "-" * 60)
    for t in types:
        h = final[t]["high"]
        m = final[t]["medium"]
        n = final[t]["normal"]
        print(f"  {t:<25}  {h:>6}  {m:>8}  {n:>8}  {h+m+n:>7}")

    print(f"\n  Sauvegarde -> {DATASET_PATH}")
    print("=" * 65)


if __name__ == "__main__":
    main()
